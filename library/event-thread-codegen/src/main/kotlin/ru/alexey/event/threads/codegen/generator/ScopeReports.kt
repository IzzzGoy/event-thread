package ru.alexey.event.threads.codegen.generator

import ru.alexey.event.threads.codegen.generator.TypeResolver.Companion.containerName
import ru.alexey.event.threads.codegen.model.ArgDef
import ru.alexey.event.threads.codegen.model.HandlerModel
import ru.alexey.event.threads.codegen.model.HandlerOutput
import ru.alexey.event.threads.codegen.model.ScopeDocument
import ru.alexey.event.threads.codegen.model.ScopeModel

/**
 * Human- (and agent-) readable views of a schema, written next to the generated code:
 * - [diagram] - the event flow as a Mermaid flowchart (`scopes.md`);
 * - [tasks] - per scope, what an implementation has to provide, with the schema's context for
 *   each piece (`tasks/<Scope>.md`) - a checklist for a developer, a self-contained brief for an
 *   AI agent; the generated contract tests check the result.
 */
object ScopeReports {

    fun diagram(document: ScopeDocument): String = buildString {
        appendLine("# Event flow")
        appendLine()
        appendLine("Schema ${document.version ?: "(unversioned)"}, format ${document.format}. Generated by event-thread-codegen.")
        appendLine()
        appendLine("```mermaid")
        appendLine("flowchart LR")
        val consumers = document.scopes.flatMap { s -> s.consumes.map { it to s.name } }.groupBy({ it.first }, { it.second })
        document.scopes.forEach { scope ->
            appendLine("  subgraph ${id(scope.name)}[\"${scope.name}${scope.params?.let { " (params)" } ?: ""}\"]")
            scope.handlers.map { it.input.name }.distinct().forEach { appendLine("    ${id(scope.name, it)}([${short(it)}])") }
            (scope.handlers.mapNotNull { it.output.writes } + scope.derived.map { it.state }).distinct().forEach {
                appendLine("    ${id(scope.name, "c:" + containerName(it))}[(${containerName(it).replaceFirstChar(Char::lowercaseChar)})]")
            }
            scope.handlers.forEach { h ->
                val from = id(scope.name, h.input.name)
                when (val out = h.output) {
                    is HandlerOutput.Data -> appendLine("    $from --> ${id(scope.name, "c:" + containerName(out.type))}")
                    is HandlerOutput.Event -> {
                        val to = id(scope.name, out.event.name)
                        if (scope.handlers.none { it.input.name == out.event.name }) appendLine("    $to([${short(out.event.name)}])")
                        appendLine("    $from -- emits --> $to")
                    }
                    is HandlerOutput.Request -> {
                        val call = id(scope.name, h.input.name, "call")
                        appendLine("    $call{{\"${out.call}\"}}")
                        appendLine("    $from --> $call --> ${id(scope.name, "c:" + containerName(out.into))}")
                        out.emits.forEach { e ->
                            val to = id(scope.name, e.name)
                            if (scope.handlers.none { it.input.name == e.name }) appendLine("    $to([${short(e.name)}])")
                            appendLine("    $call -- emits --> $to")
                        }
                    }
                    HandlerOutput.None -> appendLine("    $from --> ${id(scope.name, h.input.name, "fx")}{{side effect}}")
                }
                h.reads.forEach { appendLine("    ${id(scope.name, "c:" + containerName(it))} -. read .-> $from") }
            }
            scope.derived.forEach { d ->
                d.from.forEach { appendLine("    ${id(scope.name, "c:" + containerName(it))} -. derive .-> ${id(scope.name, "c:" + containerName(d.state))}") }
            }
            appendLine("  end")
        }
        document.scopes.forEach { scope ->
            scope.handlers.flatMap { h -> h.output.cascades.map { it.name } }.distinct().forEach { event ->
                consumers[event].orEmpty().filter { it != scope.name }.forEach { target ->
                    appendLine("  ${id(scope.name, event)} -. routed .-> ${id(target, event)}")
                }
            }
            scope.dependsOn.filter { '.' !in it }.forEach { appendLine("  ${id(scope.name)} == dependsOn ==> ${id(it)}") }
        }
        appendLine("```")
    }

    /** Per scope (keyed by file name): what to implement. */
    fun tasks(packageName: String, document: ScopeDocument): Map<String, String> {
        val context = GeneratorContext(packageName, document.scopes, remote = document.remote)
        val generator = ScopeGenerator(packageName)
        return document.scopes.associate { scope -> "${scope.name}.md" to task(context, generator, scope, document) }
    }

    private fun task(context: GeneratorContext, generator: ScopeGenerator, scope: ScopeModel, document: ScopeDocument): String = buildString {
        val base = ScopeGenerator.className(scope)
        val params = scope.params?.let { context.types.typeOf(it).toString() }
        appendLine("# ${scope.name} - implementation tasks")
        appendLine()
        scope.description?.let { appendLine(it); appendLine() }
        appendLine("Schema ${document.version ?: "(unversioned)"}. Implement `${base}Bindings` (`${context.packages.scopes}`) - or bind each piece in a DependencyProvider for `${base}DependencyBindings`.")
        params?.let { appendLine("Params: `$it` - passed to every binding.") }
        if (scope.dependsOn.isNotEmpty()) appendLine("Loading it also loads: ${scope.dependsOn.joinToString { "`$it`" }}.")
        if (scope.consumes.isNotEmpty()) appendLine("Receives from other scopes: ${scope.consumes.joinToString { "`${short(it)}`" }}.")
        appendLine()

        val members = generator.membersOf(context, scope)
        appendLine("## Containers")
        appendLine()
        members.filter { it.kind == ScopeGenerator.Kind.Container }.forEach { m ->
            val c = context.containers.values.first { it.className == m.returns }
            val derivedFrom = c.from?.joinToString { context.container(it).property }
            val initial = scope.initial[m.name]
            val requested = scope.handlers.any { (it.output as? HandlerOutput.Request)?.into?.let(context::container) == c }
            if (requested) {
                appendLine("- [x] `${m.name}` -> `${m.returns.simpleName}` holding `${c.state}`: a request's container, starting `RemoteData.Idle` (`${context.initialClass(c).simpleName}`); bind your own to replace it.")
            } else if (initial != null) {
                appendLine("- [x] `${m.name}` -> `${m.returns.simpleName}` holding `${c.state}`: generated from `initial` `$initial` (`${context.initialClass(c).simpleName}`); bind your own to replace it.")
            } else {
                appendLine("- [ ] `${m.name}` -> `${m.returns.simpleName}` holding `${c.state}`. " +
                    (if (derivedFrom != null) "Derived from $derivedFrom: supply `source` and `transforms` over them." else "Supply `source` - its initial state."))
            }
        }
        appendLine()
        appendLine("## Handlers")
        appendLine()
        scope.handlers.forEach { h -> appendLine(handlerTask(context, h)) }
        appendLine()
        appendLine("## Done when")
        appendLine()
        appendLine("A test extending `${base}Contract` passes: every binding provided, relations registered, every example below holding.")
    }

    private fun handlerTask(context: GeneratorContext, h: HandlerModel): String = buildString {
        val handler = context.handlerOf(h)
        val name = handler.className.simpleName
        val what = when (val out = h.output) {
            is HandlerOutput.Data -> "on `${short(h.input.name)}`, compute the new `${context.container(out.type).property}` (`${context.container(out.type).state}`) in `process(event, state)`"
            is HandlerOutput.Event -> "on `${short(h.input.name)}`, return the `${short(out.event.name)}` events to emit (or none) from `cascade(input)`"
            is HandlerOutput.Request -> "generated from the request `${out.call}`"
            HandlerOutput.None -> "on `${short(h.input.name)}`, perform the side effect in `handle(event)`"
        }
        val rule = h.rule
        if (h.output is HandlerOutput.Request) {
            append("- [x] `${name.replaceFirstChar(Char::lowercaseChar)}` -> `$name`: $what (`${handler.ruleClassName.simpleName}`) into `${context.container(h.output.writes!!).property}`; bind your own to replace it.")
        } else if (rule != null) {
            // Generated - nothing to write unless the default is to be replaced.
            append("- [x] `${name.replaceFirstChar(Char::lowercaseChar)}` -> `$name`: generated from the rule `$rule` (`${handler.ruleClassName.simpleName}`); bind your own to replace it.")
        } else {
            append("- [ ] `${name.replaceFirstChar(Char::lowercaseChar)}` -> `$name`: $what.")
        }
        if (h.reads.isNotEmpty()) append(" Reads ${h.reads.joinToString { "`${context.container(it).property}`" }} (snapshots).")
        if (h.input.args.isNotEmpty()) append(" Event args: ${h.input.args.joinToString { "`${it.fieldName}: ${context.types.typeOf(it)}`" }}.")
        h.examples.forEachIndexed { i, ex ->
            append("\n  - Example `${ex.name ?: i}`:")
            ex.given?.let { append(" given `$it`;") }
            if (ex.reads.isNotEmpty()) append(" reads `${kotlinx.serialization.json.JsonObject(ex.reads)}`;")
            append(" event `${ex.event ?: "(object)"}`")
            ex.respond?.let { append(" responding `$it`") }
            ex.fail?.let { append(" failing `$it`") }
            ex.expect?.let { append(" -> `$it`") }
            ex.emits?.let { append(" -> emits `$it`") }
        }
    }

    private fun short(event: String) = event.substringAfterLast('.')

    private fun id(vararg parts: String) = parts.joinToString("_") { it.replace(Regex("[^A-Za-z0-9]"), "_") }
}
